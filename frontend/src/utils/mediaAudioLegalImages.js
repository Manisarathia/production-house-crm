// 1. Resolve Post-Production Picture
export function resolvePostProductionPicture(item = {}) {
  if (typeof item === 'string') {
    const key = item.toLowerCase().trim();
    for (const [proj, url] of Object.entries(PROJECT_POSTERS)) {
      if (key.includes(proj) || proj.includes(key)) return url;
    }
    return STAGE_IMAGES['Color Grading (DI)'];
  }
  if (item?.image && typeof item.image === 'string' && item.image.trim()) {
    return item.image;
  }
  const proj = (item?.project || item?.projectRef || '').toLowerCase().trim();
  for (const [key, url] of Object.entries(PROJECT_POSTERS)) {
    if (proj && (proj.includes(key) || key.includes(proj))) return url;
  }
  const stage = item?.stage || item?.description || '';
  if (STAGE_IMAGES[stage]) return STAGE_IMAGES[stage];
  const title = (item?.title || item?.name || '').toLowerCase();
  if (title.includes('color') || title.includes('di')) return STAGE_IMAGES['Color Grading (DI)'];
  if (title.includes('sound') || title.includes('atmos')) return STAGE_IMAGES['Sound Design & Atmos Mix'];
  if (title.includes('vfx') || title.includes('cgi')) return STAGE_IMAGES['VFX Compositing'];
  if (title.includes('edit')) return STAGE_IMAGES['Offline Edit'];
  return 'https://images.unsplash.com/photo-1574717024653-61fd2cf4d44d?auto=format&fit=crop&w=800&h=450&q=85';
}

